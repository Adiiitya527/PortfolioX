"""PortfolioX Market API: a small REST server for the Android app's RemoteMarketDataSource.

Run:  uvicorn app.main:app --host 0.0.0.0 --port 8000
Docs: http://localhost:8000/docs (interactive OpenAPI UI generated by FastAPI)

Money is sent as JSON strings ("231.45"), not numbers: JSON numbers are usually parsed as
binary floating point, which can't hold most decimal amounts exactly.
"""

from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from typing import Literal

from fastapi import FastAPI, HTTPException, Query
from pydantic import BaseModel

from . import market

app = FastAPI(title="PortfolioX Market API", version="1.0.0")


class StockOut(BaseModel):
    symbol: str
    name: str
    exchange: str
    sector: str


class QuoteOut(BaseModel):
    symbol: str
    price: Decimal
    previous_close: Decimal
    open: Decimal
    day_high: Decimal
    day_low: Decimal
    timestamp: datetime


class PricePointOut(BaseModel):
    timestamp: datetime
    close: Decimal


class HistoryOut(BaseModel):
    symbol: str
    range: str
    points: list[PricePointOut]


def _stock_out(stock: market.SampleStock) -> StockOut:
    return StockOut(symbol=stock.symbol, name=stock.name, exchange=stock.exchange, sector=stock.sector)


def _require(symbol: str) -> market.SampleStock:
    stock = market.find(symbol)
    if stock is None:
        raise HTTPException(status_code=404, detail=f"Unknown stock symbol: {symbol}")
    return stock


@app.get("/health")
def health() -> dict:
    return {"status": "ok"}


@app.get("/stocks", response_model=list[StockOut])
def list_stocks(query: str = "") -> list[StockOut]:
    """All stocks, or those whose symbol or name contains `query`."""
    return [_stock_out(s) for s in market.search(query)]


@app.get("/stocks/{symbol}", response_model=StockOut)
def get_stock(symbol: str) -> StockOut:
    return _stock_out(_require(symbol))


@app.get("/quotes", response_model=list[QuoteOut])
def get_quotes(symbols: str = Query(..., description="Comma-separated symbols, e.g. AAPL,MSFT")) -> list[QuoteOut]:
    """Latest prices. Unknown symbols are skipped rather than failing the whole request."""
    now = market.utc_now()
    requested = [s.strip() for s in symbols.split(",") if s.strip()]
    stocks = [stock for symbol in requested if (stock := market.find(symbol)) is not None]
    return [QuoteOut(**market.quote(stock, now)) for stock in stocks]


@app.get("/stocks/{symbol}/history", response_model=HistoryOut)
def get_history(symbol: str, range: Literal["1W", "1M", "3M", "1Y"] = "1M") -> HistoryOut:  # noqa: A002
    stock = _require(symbol)
    points = market.history(stock, range, market.utc_now())
    return HistoryOut(symbol=stock.symbol, range=range, points=[PricePointOut(**p) for p in points])
